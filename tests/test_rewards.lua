-- Tests SIMULÉS des récompenses : attribution unique, inventaire plein, file persistante, livraison ultérieure,
-- reconnexion, redémarrage, arrêt brutal, objet inexistant. L'inventaire du joueur n'est pas persisté par le mock
-- (comme le moteur, il est sauvegardé à part) : on vérifie le journal et la file, c'est-à-dire l'absence de doublon.
local T = ...

local STUFF = { { "default:stone", "node" }, { "default:dirt", "node" }, { "default:cobble", "node" } }

local function env_book(extra)
	local opts = { mods = { "default", "farming" }, all_items = true, items = STUFF }
	for k, v in pairs(extra or {}) do opts[k] = v end
	return T.env(opts)
end

local function two_quests(Q)
	Q.register_quest({ id = "ch06.t_a", title = "A", trigger = { type = "dig", items = "default:stone" },
		reward = { items = { "default:apple 3" }, title = "Titre A" } })
	Q.register_quest({ id = "ch06.t_b", title = "B", trigger = { type = "dig", items = "default:dirt" },
		reward = { items = { "default:torch 4" } } })
end

local function pending_ids(env, name)
	local out = {}
	for _, p in ipairs(env.Q.rewards.pending(name)) do out[#out + 1] = p.q end
	return table.concat(out, ",")
end

T.describe("attribution", function()
	T.it("attribution normale : objets dans l'inventaire, journal, titre et statut « livrée »", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:dig("alice", "default:stone")
		T.eq(env:count("alice", "default:apple"), 3)
		local rec = env.Q.storage.get("alice")
		T.ok(rec.rewarded["ch06.t_a"], "journal")
		T.ok(rec.delivered["ch06.t_a"], "livraison notée")
		T.eq(rec.titles["ch06.t_a"], "Titre A")
		T.eq(#rec.pending, 0)
		T.eq(env.Q.rewards.status("alice", env.Q.get_quest("ch06.t_a")), "delivered")
		T.eq(env.Q.rewards.status("alice", env.Q.get_quest("ch06.t_b")), "none")
	end)

	T.it("attribution unique : grant() refuse une seconde fois, même après réinitialisation de la quête", function()
		local env = env_book({ before_finalize = two_quests, settings = { ["minerland_quests.allow_reset"] = true } })
		env:join("alice")
		env:join("admin", { interact = true, minerland_quests_admin = true })
		env:dig("alice", "default:stone")
		local q = env.Q.get_quest("ch06.t_a")
		T.eq(env.Q.rewards.grant("alice", q), false, "journal : déjà attribuée")
		env:chat("admin", "mlq_reset", "alice ch06.t_a")
		T.eq(env:state("alice", "ch06.t_a"), "available", "quête réinitialisée")
		env:dig("alice", "default:stone")
		T.eq(env:state("alice", "ch06.t_a"), "done", "refaite")
		T.eq(env:count("alice", "default:apple"), 3, "mais jamais récompensée une seconde fois")
	end)

	T.it("deux joueurs ont chacun leur récompense et leur journal", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice") env:join("bob")
		env:dig("alice", "default:stone")
		T.eq(env:count("alice", "default:apple"), 3)
		T.eq(env:count("bob", "default:apple"), 0)
		env:dig("bob", "default:stone")
		T.eq(env:count("bob", "default:apple"), 3)
	end)

	T.it("un objet de récompense inexistant est retiré sans bloquer la livraison des autres", function()
		local env = env_book({ before_finalize = function(Q)
			Q.register_quest({ id = "ch06.t_a", title = "A", trigger = { type = "dig", items = "default:stone" },
				reward = { items = { "absent:cadeau 2", "default:apple 1" } } })
		end })
		env:join("alice")
		env:dig("alice", "default:stone")
		T.eq(env:state("alice", "ch06.t_a"), "done")
		T.eq(env:count("alice", "default:apple"), 1)
		T.eq(env:count("alice", "absent:cadeau"), 0)
		local logged = false
		for _, l in ipairs(env.mock.log) do
			logged = logged or (l.level == "warning" and l.msg:find("absent:cadeau", 1, true))
		end
		T.ok(logged, "avertissement journalisé")
	end)

	T.it("quête sans objet : titre seul, aucune file d'attente", function()
		local env = env_book({ before_finalize = function(Q)
			Q.register_quest({ id = "ch06.t_t", title = "T", trigger = { type = "dig", items = "default:stone" },
				reward = { title = "Seulement un titre" } })
		end })
		env:join("alice")
		env:dig("alice", "default:stone")
		T.eq(env.Q.storage.get("alice").titles["ch06.t_t"], "Seulement un titre")
		T.eq(env.Q.rewards.pending_count("alice"), 0)
	end)
end)

T.describe("inventaire plein et file de livraison", function()
	T.it("inventaire plein : la récompense est mise en attente, signalée, puis livrée automatiquement", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone")
		T.eq(env:state("alice", "ch06.t_a"), "done", "la quête est validée quand même")
		T.eq(env:count("alice", "default:apple"), 0)
		T.eq(pending_ids(env, "alice"), "ch06.t_a")
		T.eq(env.Q.rewards.status("alice", env.Q.get_quest("ch06.t_a")), "pending")
		T.ok(env.Q.storage.get("alice").rewarded["ch06.t_a"], "déjà journalisée")
		T.contains(env:chat_log("alice"), "Inventaire plein", "message d'inventaire plein")
		env:step(10)
		T.eq(env.Q.rewards.pending_count("alice"), 1, "toujours plein : toujours en attente, rien au sol")
		env:clear_inventory("alice")
		env:step(10)
		T.eq(env.Q.rewards.pending_count("alice"), 0)
		T.eq(env:count("alice", "default:apple"), 3)
		T.eq(env.Q.rewards.status("alice", env.Q.get_quest("ch06.t_a")), "delivered")
	end)

	T.it("plusieurs récompenses en attente sont livrées dans l'ordre", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone") env:dig("alice", "default:dirt")
		T.eq(pending_ids(env, "alice"), "ch06.t_a,ch06.t_b")
		env:clear_inventory("alice")
		env:step(10)
		T.eq(env.Q.rewards.pending_count("alice"), 0)
		T.eq(env:count("alice", "default:apple"), 3)
		T.eq(env:count("alice", "default:torch"), 4)
	end)

	T.it("le bouton « recevoir mes récompenses » relance la livraison sans rien attribuer", function()
		local env = env_book({ before_finalize = two_quests, ui = true })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone")
		env:clear_inventory("alice")
		env:fields("alice", "minerland_quests:book", { mlq_deliver = "x" })
		T.eq(env:count("alice", "default:apple"), 3)
		env:fields("alice", "minerland_quests:book", { mlq_deliver = "x" })
		T.eq(env:count("alice", "default:apple"), 3, "pas de seconde livraison")
	end)

	T.it("reconnexion : la file survit à la déconnexion et se vide à la reconnexion", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone")
		env:leave("alice")
		T.eq(env.Q.rewards.pending_count("alice"), 1, "file conservée hors ligne")
		env:join("alice")   -- inventaire neuf (vide) : le mock ne persiste pas les inventaires
		env:step(5)
		T.eq(env.Q.rewards.pending_count("alice"), 0)
		T.eq(env:count("alice", "default:apple"), 3)
	end)
end)

T.describe("redémarrage et arrêt brutal", function()
	T.it("redémarrage propre avec file en attente : livrée une seule fois à la reconnexion", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone")
		local env2 = env:restart()
		T.eq(env2.Q.rewards.pending_count("alice"), 1, "file lue dans le stockage")
		T.eq(env2:state("alice", "ch06.t_a"), "done")
		env2:join("alice")
		env2:step(5)
		T.eq(env2.Q.rewards.pending_count("alice"), 0)
		T.eq(env2:count("alice", "default:apple"), 3)
		env2:step(30)
		T.eq(env2:count("alice", "default:apple"), 3, "aucune seconde livraison")
	end)

	T.it("arrêt brutal juste après la validation : quête et journal conservés, jamais de doublon", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:dig("alice", "default:stone")
		local env2 = env:crash_restart()
		local rec = env2.Q.storage.get("alice")
		T.ok(rec.done["ch06.t_a"], "quête conservée")
		T.ok(rec.rewarded["ch06.t_a"], "journal conservé")
		env2:join("alice")
		env2:step(10)
		T.eq(env2.Q.rewards.pending_count("alice"), 0)
		T.eq(env2.Q.rewards.grant("alice", env2.Q.get_quest("ch06.t_a")), false, "pas de nouvelle attribution")
		T.eq(env2:count("alice", "default:apple"), 0, "récompense déjà livrée avant l'arrêt : non redonnée")
	end)

	T.it("un objet disparu du serveur entre-temps est ignoré à la livraison (le reste est livré)", function()
		local env = env_book({ before_finalize = two_quests })
		env:join("alice")
		env:fill_inventory("alice", "default:cobble")
		env:dig("alice", "default:stone")
		env.Q.rewards.pending("alice")[1].items = { "absent:vieux 1", "default:apple 3" }
		env:clear_inventory("alice")
		env:step(10)
		T.eq(env.Q.rewards.pending_count("alice"), 0)
		T.eq(env:count("alice", "default:apple"), 3)
	end)
end)
